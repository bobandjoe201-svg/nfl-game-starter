"""NFL Game Model v0.1: deterministic spread/total *score* baseline.

Works with CSVs generated by nfl_game_data_starter.py, unchanged.

Train: 2022-2024 completed regular-season games (weeks 2+)
Test : 2025 completed regular-season games (weeks 2+; never used to train)
Live : 2026 Week 6, only while every game in that week remains unplayed.

No injuries, expected starters, weather, sportsbook-specific odds, calibrated
cover probabilities, or ROI estimates. Historical schedule odds are closing
numbers: NOT evidence a bet was available at a particular pregame time.
"""

from __future__ import annotations

import argparse
import hashlib
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_absolute_error
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

MODEL_VERSION = "nfl-game-v0.1-ridge"
TRAIN_YEARS = (2022, 2023, 2024)
TEST_YEAR = 2025
PREDICTION_YEAR = 2026
PREDICTION_WEEK = 6

# Preselected predictors: never include results or closing sportsbook odds.
PREDICTORS = [
    "home_rest", "away_rest", "home_prior_games", "away_prior_games",
    "home_off_epa_play", "home_off_success_rate", "home_off_pass_rate",
    "home_off_explosive_rate", "home_def_epa_allowed",
    "home_def_success_allowed", "home_def_explosive_allowed",
    "away_off_epa_play", "away_off_success_rate", "away_off_pass_rate",
    "away_off_explosive_rate", "away_def_epa_allowed",
    "away_def_success_allowed", "away_def_explosive_allowed",
]
KEY = ["season", "week", "game_id"]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def rmse(actual: pd.Series | np.ndarray, predicted: np.ndarray) -> float:
    return float(np.sqrt(np.mean((np.asarray(actual) - predicted) ** 2)))


def build_model() -> object:
    # Training-year medians only: imputations never learn from holdout/future rows.
    return make_pipeline(
        SimpleImputer(strategy="median"),
        StandardScaler(),
        Ridge(alpha=10.0),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--features", type=Path, default=Path("output/pregame_features.csv"))
    parser.add_argument("--labels", type=Path, default=Path("output/historical_labels.csv"))
    parser.add_argument("--outdir", type=Path, default=Path("output/model_v01"))
    args = parser.parse_args()

    features = pd.read_csv(args.features)
    labels = pd.read_csv(args.labels)

    missing = set(KEY + PREDICTORS) - set(features.columns)
    if missing:
        raise ValueError(f"Missing expected feature columns: {sorted(missing)}")
    missing_labels = set(KEY + ["home_margin", "actual_total", "home_score", "away_score"]) - set(labels.columns)
    if missing_labels:
        raise ValueError(f"Missing expected label columns: {sorted(missing_labels)}")
    if features.duplicated(KEY).any() or labels.duplicated(KEY).any():
        raise ValueError("Duplicate game keys in input CSVs")

    # Only training/test code gets outcomes. Predictors are a fixed whitelist.
    df = features.merge(
        labels[KEY + ["home_score", "away_score", "home_margin", "actual_total", "total_line"]],
        on=KEY, how="left", validate="one_to_one", indicator=True,
    )
    if not df["_merge"].eq("both").all():
        raise ValueError("Feature rows missing matching label rows")
    df = df.drop(columns="_merge")

    # Week 1 lacks same-season history, so exclude it from this first model.
    train = df[df.season.isin(TRAIN_YEARS) & (df.week >= 2)].copy()
    test = df[(df.season == TEST_YEAR) & (df.week >= 2)].copy()
    week6 = df[(df.season == PREDICTION_YEAR) & (df.week == PREDICTION_WEEK)].copy()
    for name, subset in [("training", train), ("holdout", test)]:
        if subset.empty or subset[["home_margin", "actual_total"]].isna().any().any():
            raise ValueError(f"{name} contains no usable games or missing final scores")
    if week6.empty:
        raise ValueError("No 2026 Week 6 games found")
    if week6[["home_score", "away_score"]].notna().any().any():
        raise ValueError("2026 Week 6 has a recorded result. Refusing to label late forecasts as pregame.")
    if week6[PREDICTORS].isna().any().any():
        raise ValueError("2026 Week 6 predictor data missing; inspect before forecasting")

    # Fix the regression family and regularization BEFORE scoring the holdout.
    margin_model = build_model()
    total_model = build_model()
    margin_model.fit(train[PREDICTORS], train["home_margin"])
    total_model.fit(train[PREDICTORS], train["actual_total"])

    test = test.assign(
        pred_home_margin=margin_model.predict(test[PREDICTORS]),
        pred_total=total_model.predict(test[PREDICTORS]),
    )
    forecasts = week6.assign(
        pred_home_margin=margin_model.predict(week6[PREDICTORS]),
        pred_total=total_model.predict(week6[PREDICTORS]),
    )
    forecasts["pred_home_points"] = (forecasts.pred_total + forecasts.pred_home_margin) / 2
    forecasts["pred_away_points"] = (forecasts.pred_total - forecasts.pred_home_margin) / 2

    args.outdir.mkdir(parents=True, exist_ok=True)
    audit = test[KEY + ["home_team", "away_team", "home_margin", "actual_total", "pred_home_margin", "pred_total", "total_line"]].copy()
    audit.to_csv(args.outdir / "holdout_2025_predictions.csv", index=False)

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    live_file = args.outdir / f"week6_2026_predictions_{timestamp}.csv"
    live_cols = KEY + ["home_team", "away_team", "gameday", "pred_home_margin", "pred_total", "pred_home_points", "pred_away_points"]
    forecasts[live_cols].assign(
        model_version=MODEL_VERSION,
        generated_at_utc=timestamp,
        features_sha256=sha256(args.features),
        labels_sha256=sha256(args.labels),
    ).sort_values(["gameday", "game_id"]).round(3).to_csv(live_file, index=False)

    print(f"Model: {MODEL_VERSION} | training: {len(train)} | 2025 holdout: {len(test)}")
    print(f"Margin MAE: {mean_absolute_error(test.home_margin, test.pred_home_margin):.2f}")
    print(f"Margin RMSE: {rmse(test.home_margin, test.pred_home_margin):.2f}")
    print(f"Total MAE: {mean_absolute_error(test.actual_total, test.pred_total):.2f}")
    print(f"Total RMSE: {rmse(test.actual_total, test.pred_total):.2f}")
    has_total_line = test.total_line.notna()
    if has_total_line.any():
        closing_mae = mean_absolute_error(test.loc[has_total_line, "actual_total"], test.loc[has_total_line, "total_line"])
        print(f"Closing total-line MAE (benchmark, not a placed bet): {closing_mae:.2f} | games: {has_total_line.sum()}")
    print("Note: positive home margin = home team projected to win by that many points.")
    print(f"\nSaved 2025 holdout report: {args.outdir / 'holdout_2025_predictions.csv'}")
    print(f"Saved {len(forecasts)} 2026 Week 6 forecasts: {live_file}")
    print("No betting selections or ROI figures are generated.")


if __name__ == "__main__":
    main()
